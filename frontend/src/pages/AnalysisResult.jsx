import { useState } from "react";
import { useNavigate } from "react-router-dom";
import { api } from "../api.js";
import { useAppContext } from "../AppContext.jsx";
import RiskBadge from "../components/RiskBadge.jsx";
import EvidenceCard from "../components/EvidenceCard.jsx";
import Icon from "../components/Icon.jsx";

const CHUNK_REF_RE = /\s*\[([A-Za-z0-9_]+)\]/g;

function parseCitedStatement(text) {
  const ids = [];
  const clean = text.replace(CHUNK_REF_RE, (_, id) => {
    ids.push(id);
    return "";
  });
  return { clean: clean.trim(), ids };
}

function CitedStatementList({ items, evidence }) {
  if (!items || items.length === 0) {
    return <p className="empty-note">None reported.</p>;
  }
  const byId = Object.fromEntries((evidence || []).map((e) => [e.chunk_id, e]));
  return (
    <ul className="statement-list">
      {items.map((s, i) => {
        const { clean, ids } = parseCitedStatement(s);
        const sources = [...new Set(ids)].map((id) => byId[id]).filter(Boolean);
        return (
          <li key={i}>
            {clean}
            {sources.length > 0 && (
              <span className="source-chips">
                {sources.map((src) => (
                  <a
                    key={src.chunk_id}
                    href={src.url}
                    target="_blank"
                    rel="noreferrer"
                    className={`source-chip source-${src.source_type === "label" ? "label" : "literature"}`}
                    title={`${src.section} — view on ${src.source_name}`}
                  >
                    <Icon name="link" size={10} /> {src.source_name}
                  </a>
                ))}
              </span>
            )}
          </li>
        );
      })}
    </ul>
  );
}

function GeneratedByBadge({ generatedBy }) {
  const isLlm = generatedBy?.startsWith("llm:");
  const label = isLlm ? `Live LLM — ${generatedBy.slice(4)}` : "Template fallback (no live LLM)";
  return (
    <span className={`generation-badge ${isLlm ? "is-llm" : "is-template"}`} title={
      isLlm
        ? "This report was generated by a live LLM call via OpenRouter."
        : "The live LLM call was not used (unchecked, unavailable, or it failed) — this report was assembled by the deterministic, fully-cited template generator instead."
    }>
      <Icon name={isLlm ? "brain" : "database"} size={12} />
      {label}
    </span>
  );
}

const VERDICT_TEXT = {
  lower_concern:
    "Nothing in this patient's profile matched a documented concern in the retrieved evidence — this does not rule out risk, but no specific conflict was found.",
  moderate_concern:
    "Some patient-specific factors overlap with documented cautions for this medication — worth discussing before continuing.",
  higher_concern:
    "Patient-specific factors align with documented higher-risk evidence for this medication — this combination warrants closer clinical review before use.",
  indeterminate:
    "There isn't enough retrieved evidence or patient data to assess contextual concern reliably here.",
};

function splitEffectsByAdvantage(items, evidence) {
  const byId = Object.fromEntries((evidence || []).map((e) => [e.chunk_id, e]));
  const advantages = [];
  const concerns = [];
  for (const item of items || []) {
    const { clean, ids } = parseCitedStatement(item);
    const sections = ids.map((id) => byId[id]?.section).filter(Boolean);
    (sections.includes("Indications and Usage") ? advantages : concerns).push(clean);
  }
  return { advantages, concerns };
}

function Conclusion({ result }) {
  const category = result.risk_category || "indeterminate";
  const { advantages, concerns } = splitEffectsByAdvantage(result.documented_effects, result.evidence);
  const problems = [
    ...concerns,
    ...(result.patient_relevant_risks || []).map((s) => parseCitedStatement(s).clean),
    ...(result.contraindications_or_warnings || []).map((s) => parseCitedStatement(s).clean),
  ].slice(0, 4);

  return (
    <div className={`conclusion-box conclusion-${category}`}>
      <div className="conclusion-row">
        <RiskBadge category={result.risk_category} probability={result.risk_probability} />
        <GeneratedByBadge generatedBy={result.generated_by} />
      </div>
      <p className="conclusion-verdict">{VERDICT_TEXT[category] || VERDICT_TEXT.indeterminate}</p>
      <div className="conclusion-grid">
        <div>
          <div className="conclusion-col-title">
            <Icon name="checkCircle" size={13} /> Advantages — why this drug is used
          </div>
          {advantages.length ? (
            <ul className="statement-list">
              {advantages.map((a, i) => (
                <li key={i}>{a}</li>
              ))}
            </ul>
          ) : (
            <p className="empty-note">No indication-specific evidence retrieved.</p>
          )}
        </div>
        <div>
          <div className="conclusion-col-title">
            <Icon name="alertTriangle" size={13} /> Problem — what's driving the concern
          </div>
          {problems.length ? (
            <ul className="statement-list">
              {problems.map((c, i) => (
                <li key={i}>{c}</li>
              ))}
            </ul>
          ) : (
            <p className="empty-note">No specific concern identified in retrieved evidence.</p>
          )}
        </div>
      </div>
      <p className="conclusion-disclaimer">
        <Icon name="shield" size={12} /> Not a recommendation to start, continue, or stop this
        medication — a qualified clinician should weigh this against the full clinical picture.
      </p>
    </div>
  );
}

function FlagList({ items }) {
  if (!items || items.length === 0) {
    return <p className="empty-note">None flagged.</p>;
  }
  return (
    <ul className="statement-list flag-list">
      {items.map((s, i) => (
        <li key={i}>{s}</li>
      ))}
    </ul>
  );
}

function ReportBody({ result }) {
  return (
    <div>
      <div className="section-label">
        <Icon name="checkCircle" size={14} /> Conclusion
      </div>
      <Conclusion result={result} />

      <div className="section-label">
        <Icon name="activity" size={14} /> Summary
      </div>
      <RiskBadge category={result.risk_category} probability={result.risk_probability} />
      <p style={{ marginTop: "0.65rem", fontSize: "0.9rem", lineHeight: 1.55, color: "var(--color-text-soft)" }}>
        {result.reasoning_summary}
      </p>

      <div className="section-label">
        <Icon name="pill" size={14} /> Documented drug effects
      </div>
      <CitedStatementList items={result.documented_effects} evidence={result.evidence} />

      <div className="section-label">
        <Icon name="user" size={14} /> Patient-specific considerations
      </div>
      <CitedStatementList items={result.patient_relevant_risks} evidence={result.evidence} />

      <div className="section-label">
        <Icon name="alertTriangle" size={14} /> Warnings / contraindications
      </div>
      <CitedStatementList items={result.contraindications_or_warnings} evidence={result.evidence} />

      <div className="section-label">
        <Icon name="dna" size={14} /> Dose context
      </div>
      <CitedStatementList items={result.dose_context} evidence={result.evidence} />

      <div className="section-label">
        <Icon name="helpCircle" size={14} /> Uncertainty
      </div>
      <FlagList items={result.uncertainty_flags} />

      <div className="section-label">
        <Icon name="database" size={14} /> Missing information
      </div>
      <FlagList items={result.missing_information} />

      <div className="section-label">
        <Icon name="filter" size={14} /> Citation faithfulness
      </div>
      <p style={{ fontSize: "0.8rem", color: "var(--color-muted)" }}>
        coverage: <strong>{(result.citation_metrics?.coverage * 100).toFixed(0)}%</strong> ·
        unsupported claim rate:{" "}
        <strong>{(result.citation_metrics?.unsupported_claim_rate * 100).toFixed(0)}%</strong>
      </p>
    </div>
  );
}

export default function AnalysisResult() {
  const navigate = useNavigate();
  const { compareResult } = useAppContext();
  const [showCompare, setShowCompare] = useState(false);
  const [showQueries, setShowQueries] = useState(false);
  const [feedbackSent, setFeedbackSent] = useState(false);

  if (!compareResult) {
    return (
      <div className="card empty-state">
        <Icon name="activity" size={40} />
        <h2 style={{ marginTop: "0.6rem" }}>No analysis yet</h2>
        <p className="card-subtext">Enter a patient and target drug first, or load a demo case.</p>
        <button className="btn-primary" style={{ marginTop: "1rem" }} onClick={() => navigate("/")}>
          <Icon name="user" size={16} /> Go to Patient Input
        </button>
      </div>
    );
  }

  const { baseline, context_aware, diff_highlights } = compareResult;

  const sendFeedback = async (rating) => {
    try {
      await api.sendFeedback(context_aware.assessment_id, rating, null);
      setFeedbackSent(true);
    } catch (e) {
      console.error(e);
    }
  };

  return (
    <div>
      <div className="card">
        <div className="card-header">
          <Icon name="pill" />
          <h2>
            {context_aware.drug.generic_name}
            {context_aware.drug.dose ? ` — ${context_aware.drug.dose}` : ""}
          </h2>
        </div>
        <div className="feedback-row" style={{ marginTop: "0.3rem" }}>
          <p className="card-subtext" style={{ margin: 0 }}>
            Patient-specific medication safety assessment
          </p>
          <GeneratedByBadge generatedBy={context_aware.generated_by} />
        </div>
        <div className="feedback-row">
          <button className="btn-secondary" onClick={() => setShowCompare((v) => !v)}>
            <Icon name="activity" size={15} />
            {showCompare ? "Hide" : "Show"} drug-only baseline comparison
          </button>
          <button className="btn-secondary" onClick={() => setShowQueries((v) => !v)}>
            <Icon name="filter" size={15} />
            {showQueries ? "Hide" : "Show"} generated retrieval queries
            <span className="badge-count">{context_aware.queries_used.length}</span>
          </button>
        </div>

        {showQueries && (
          <div style={{ marginTop: "0.9rem" }}>
            {context_aware.queries_used.map((q, i) => (
              <span className="query-pill" key={i} title={q.reason}>
                <Icon name="filter" size={12} />
                {q.text}
              </span>
            ))}
          </div>
        )}
      </div>

      {showCompare && (
        <div className="card">
          <div className="card-header">
            <Icon name="activity" />
            <h2>Drug-Only Baseline vs. Patient-Context RAG</h2>
          </div>
          {diff_highlights?.map((d, i) => (
            <div className="diff-banner" key={i}>
              <Icon name="alertTriangle" size={16} />
              <span>{d}</span>
            </div>
          ))}
          <div className="compare-grid">
            <div className="compare-col">
              <div className="compare-col-header">Model A — Drug-only baseline</div>
              <ReportBody result={baseline} />
            </div>
            <div className="compare-col is-context">
              <div className="compare-col-header">
                <Icon name="checkCircle" size={15} /> Model C — Patient-context + RAG
              </div>
              <ReportBody result={context_aware} />
            </div>
          </div>
        </div>
      )}

      {!showCompare && (
        <div className="card">
          <ReportBody result={context_aware} />
        </div>
      )}

      <div className="card">
        <div className="card-header">
          <Icon name="flask" />
          <h2>Evidence <span className="badge-count">{context_aware.evidence.length}</span></h2>
        </div>
        <div style={{ marginTop: "0.8rem" }}>
          {context_aware.evidence.map((chunk) => (
            <EvidenceCard key={chunk.chunk_id} chunk={chunk} />
          ))}
        </div>
      </div>

      <div className="card">
        <div className="card-header">
          <Icon name="checkCircle" />
          <h2>Evaluator feedback</h2>
        </div>
        {feedbackSent ? (
          <p className="feedback-sent">
            <Icon name="checkCircle" size={16} /> Feedback recorded. Thank you.
          </p>
        ) : (
          <div className="feedback-row">
            <button className="btn-chip" onClick={() => sendFeedback("correct")}>
              Correct
            </button>
            <button className="btn-chip" onClick={() => sendFeedback("partially_correct")}>
              Partially correct
            </button>
            <button className="btn-chip" onClick={() => sendFeedback("incorrect")}>
              Incorrect
            </button>
            <button className="btn-chip" onClick={() => sendFeedback("unsupported_citation")}>
              Unsupported citation
            </button>
          </div>
        )}
      </div>
    </div>
  );
}
